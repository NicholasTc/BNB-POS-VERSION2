export function ownerMessage(message: string, language: OwnerLanguage) {
  if (language === "id") {
    if (message.startsWith("Invalid email or password"))
      return "Email atau kata sandi tidak cocok.";
    if (message === "Failed to fetch")
      return "Koneksi belum tersedia. Periksa koneksi lalu coba lagi.";
    return message;
  }
  return (
    ownerEnglish[message as OwnerText] ??
    errorEnglish[message] ??
    "The request could not be completed. Please check and try again."
  );
}
